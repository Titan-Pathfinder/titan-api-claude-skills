// Copies the skill's markdown into the Worker bundle so the MCP serves exactly
// what the Claude Code plugin ships. Runs before dev, test, typecheck and deploy.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const skillDir = new URL('../../skills/titan-swap-api/', import.meta.url).pathname;
const guides = Object.fromEntries(
  readdirSync(join(skillDir, 'references'))
    .filter((name) => name.endsWith('.md'))
    .sort()
    .map((name) => [name.replace(/\.md$/, ''), readFileSync(join(skillDir, 'references', name), 'utf8')]),
);
const skill = readFileSync(join(skillDir, 'SKILL.md'), 'utf8');

writeFileSync(
  new URL('../src/skill-content.generated.ts', import.meta.url),
  `// Generated by scripts/bundle-skill.mjs from skills/titan-swap-api. Do not edit.\n` +
    `export const SKILL: string = ${JSON.stringify(skill)};\n` +
    `export const GUIDES: Record<string, string> = ${JSON.stringify(guides, null, 2)};\n`,
);
console.log(`bundled SKILL.md + ${Object.keys(guides).length} references: ${Object.keys(guides).join(', ')}`);
